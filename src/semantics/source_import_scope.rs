//! Non-shadowing proofs for indexed package and class wildcard imports.
//!
//! Absence needs complete declarations, field facts and ancestry. An unrelated
//! imported owner must not disable a standard rule merely because it is a type
//! rather than a package; missing facts must not stand in for an empty scope.

use super::{FactStatus, SemanticProvider, SymbolId, is_type_symbol, qualified_source_type_name};
use std::collections::BTreeSet;

pub(super) fn excludes_name<P: SemanticProvider + ?Sized>(
    scope: &str,
    name: &str,
    provider: &P,
) -> bool {
    let Some(simple) = scope.rsplit('.').next().filter(|name| !name.is_empty()) else {
        return false;
    };
    let owners = provider
        .symbols_named(simple)
        .into_iter()
        .filter(|symbol| {
            is_type_symbol(&symbol.id) && qualified_source_type_name(&symbol.id) == scope
        })
        .map(|symbol| symbol.id.clone())
        .collect::<Vec<_>>();
    if provider.has_source_package(scope) {
        return owners.is_empty()
            && !provider.has_type_alias_in_package(scope, name)
            && !provider
                .symbols_named(name)
                .iter()
                .any(|symbol| symbol.id.package == scope && symbol.id.owner_path.is_empty());
    }
    let [owner] = owners.as_slice() else {
        return false;
    };
    excludes_member(
        owner,
        name,
        provider,
        &mut BTreeSet::new(),
        &mut BTreeSet::new(),
    )
}

fn excludes_member<P: SemanticProvider + ?Sized>(
    owner: &SymbolId,
    name: &str,
    provider: &P,
    active: &mut BTreeSet<SymbolId>,
    proved: &mut BTreeSet<SymbolId>,
) -> bool {
    if proved.contains(owner) {
        return true;
    }
    if !active.insert(owner.clone()) {
        return false;
    }
    let result = (|| {
        // Enum methods generated by javac have no source declaration.
        if owner.kind == "enum" && matches!(name, "values" | "valueOf") {
            return false;
        }
        if !provider.has_complete_declared_member_scope(owner)
            || !matches!(
                provider.java_field_named(owner, name),
                FactStatus::Established(false)
            )
        {
            return false;
        }
        let mut path = owner.owner_path.clone();
        path.push(owner.name.clone());
        if provider
            .symbols_named(name)
            .iter()
            .any(|symbol| symbol.id.file == owner.file && symbol.id.owner_path == path)
            || !provider.companion_members(owner, name).is_empty()
            || !provider.companion_properties(owner, name).is_empty()
        {
            return false;
        }
        let FactStatus::Established(parents) = provider.instance_contract_parents(owner) else {
            return false;
        };
        parents
            .iter()
            .all(|parent| excludes_member(parent, name, provider, active, proved))
    })();
    active.remove(owner);
    if result {
        proved.insert(owner.clone());
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::semantics::SyntaxSemanticProvider;
    use std::path::PathBuf;

    fn provider(sources: &[(&str, &str)]) -> SyntaxSemanticProvider {
        SyntaxSemanticProvider::new(
            sources
                .iter()
                .map(|(path, text)| (PathBuf::from(path), (*text).into())),
        )
    }

    #[test]
    fn complete_packages_classes_enums_nested_types_and_diamonds_exclude_unrelated_names() {
        let facts = provider(&[
            (
                "Root.java",
                "package lib; public interface Root {String LABEL=\"root\";}",
            ),
            (
                "Left.java",
                "package lib; public interface Left extends Root {}",
            ),
            (
                "Right.java",
                "package lib; public interface Right extends Root {}",
            ),
            (
                "Constants.java",
                "package lib; public class Constants implements Left,Right {public static class Nested {public static String mapOf(){return \"unrelated\";}}}",
            ),
            (
                "Choice.java",
                "package lib; public enum Choice {FIRST,SECOND}",
            ),
            (
                "OtherChoice.java",
                "package elsewhere; public enum Choice {OTHER}",
            ),
            (
                "Outer.java",
                "package lib; public class Outer {public static class Inner {}}",
            ),
            ("Empty.java", "public class Empty {}"),
        ]);
        for scope in [
            "lib",
            "lib.Constants",
            "lib.Choice",
            "lib.Outer.Inner",
            "Empty",
        ] {
            for name in ["mapOf", "listOf", "String"] {
                assert!(
                    excludes_name(scope, name, &facts),
                    "{scope} cannot hide {name}"
                );
            }
        }
        for (scope, name) in [
            ("lib.Constants", "LABEL"),
            ("lib.Constants", "Nested"),
            ("lib.Choice", "FIRST"),
            ("lib.Choice", "values"),
            ("lib.Choice", "valueOf"),
        ] {
            assert!(
                !excludes_name(scope, name, &facts),
                "{scope} supplies {name}"
            );
        }
    }

    #[test]
    fn declared_and_inherited_methods_fields_callable_fields_and_types_block_the_proof() {
        for declaration in [
            "public static String mapOf(){return \"custom\";}",
            "public static kotlin.jvm.functions.Function0<String> mapOf=()->\"custom\";",
            "public static int unrelated,mapOf;",
            "public static class mapOf {}",
        ] {
            let parent = format!("package lib; public class Parent {{{declaration}}}");
            let facts = provider(&[
                ("Parent.java", &parent),
                (
                    "Child.java",
                    "package lib; public class Child extends Parent {}",
                ),
            ]);
            for scope in ["lib.Parent", "lib.Child"] {
                assert!(
                    !excludes_name(scope, "mapOf", &facts),
                    "{scope}: {declaration}"
                );
            }
        }
        let facts = provider(&[(
            "Choice.java",
            "package lib; public enum Choice {mapOf,OTHER}",
        )]);
        assert!(!excludes_name("lib.Choice", "mapOf", &facts));
    }

    #[test]
    fn unknown_or_generated_members_incomplete_ancestry_and_cycles_cannot_prove_absence() {
        for declaration in [
            "@unknown.Generate public class Scope {}",
            "public class Scope {@unknown.Generate public static String build(){return \"x\";}}",
            "public class Scope {@lombok.Builder(builderMethodName=\"mapOf\") public static String build(){return \"x\";}}",
            "public class Scope extends unavailable.Parent {}",
            "public class Scope extends Scope {}",
            "public class Scope { public static String broken(] }",
        ] {
            let source = format!("package lib; {declaration}");
            let facts = provider(&[("Scope.java", &source)]);
            assert!(
                !excludes_name("lib.Scope", "mapOf", &facts),
                "{declaration}"
            );
        }
        let facts = provider(&[("Choice.kt", "package lib\nenum class Choice {FIRST}\n")]);
        // A field lookup is an explicit fact, not an empty default answer.
        assert!(!excludes_name("lib.Choice", "mapOf", &facts));
        assert!(!excludes_name("unavailable.Scope", "mapOf", &facts));
    }

    #[test]
    fn aliases_duplicate_owners_and_package_type_collisions_do_not_create_empty_scopes() {
        let facts = provider(&[(
            "Alias.kt",
            "package lib\ntypealias mapOf=java.util.HashMap<String,String>\n",
        )]);
        assert!(!excludes_name("lib", "mapOf", &facts));
        assert!(!excludes_name("lib.mapOf", "listOf", &facts));
        let facts = provider(&[
            ("First.java", "package lib; public class Scope {}"),
            ("Second.java", "package lib; public class Scope {}"),
        ]);
        assert!(!excludes_name("lib.Scope", "mapOf", &facts));
        let facts = provider(&[
            ("Scope.java", "package lib; public class Scope {}"),
            ("Other.java", "package lib.Scope; public class Other {}"),
        ]);
        assert!(!excludes_name("lib.Scope", "mapOf", &facts));
    }

    #[test]
    fn field_and_metadata_proofs_require_the_same_source_snapshot() {
        let path = PathBuf::from("Choice.java");
        let original = "package lib; public enum Choice {FIRST}";
        let mut facts = provider(&[("Choice.java", original)]);
        assert!(excludes_name("lib.Choice", "mapOf", &facts));
        facts
            .sources
            .insert(path, format!("{original}\n// another snapshot\n"));
        assert!(!excludes_name("lib.Choice", "mapOf", &facts));
    }
}
